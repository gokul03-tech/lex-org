"""Report endpoints: generate, get, download advisory reports."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.responses import FileResponse
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.future import select

from app.api.deps import require_user
from app.db.models import Analysis, Case, Report
from app.db.session import get_db
from app.schemas import MessageResponse, ReportResponse
from app.services.report_service import ReportGenerator

router = APIRouter()


async def _require_owned_case(
    case_id: str, user_id: str, db: AsyncSession
) -> Case:
    """Return the case only when it belongs to the given user, else 404."""
    result = await db.execute(
        select(Case).where(Case.id == case_id, Case.user_id == user_id)
    )
    case = result.scalar_one_or_none()
    if case is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Case not found",
        )
    return case


@router.post("/case/{case_id}", response_model=ReportResponse | MessageResponse)
async def generate_report(
    case_id: str,
    current_user_id: Annotated[str, Depends(require_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> ReportResponse | MessageResponse:
    """Return the report generated by the latest completed case analysis."""
    case = await _require_owned_case(case_id, current_user_id, db)
    report_result = await db.execute(
        select(Report).where(Report.case_id == case_id).order_by(Report.created_at.desc())
    )
    report = report_result.scalars().first()
    if report is None:
        analysis_result = await db.execute(
            select(Analysis)
            .where(Analysis.case_id == case_id)
            .order_by(Analysis.created_at.desc())
        )
        if analysis_result.scalars().first() is None:
            return MessageResponse(
                message="Report generation requires a completed case analysis.",
                detail="Upload a document and run analysis before generating a report.",
            )
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No report is available for the latest analysis.",
        )

    case.status = "report_generated"
    await db.commit()
    await db.refresh(report)
    return report


@router.get("/case/{case_id}", response_model=ReportResponse)
async def get_report(
    case_id: str,
    current_user_id: Annotated[str, Depends(require_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> Report:
    """Get the latest persisted report for a case."""
    await _require_owned_case(case_id, current_user_id, db)
    result = await db.execute(
        select(Report).where(Report.case_id == case_id).order_by(Report.created_at.desc())
    )
    report = result.scalars().first()
    if report is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No report has been generated for this case.",
        )
    return report


@router.get("/case/{case_id}/download")
async def download_report(
    case_id: str,
    current_user_id: Annotated[str, Depends(require_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
    format: str = "pdf",
) -> FileResponse:
    """Download the latest report as PDF or JSON."""
    case = await _require_owned_case(case_id, current_user_id, db)
    result = await db.execute(
        select(Report).where(Report.case_id == case_id).order_by(Report.created_at.desc())
    )
    report = result.scalars().first()
    if report is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No report has been generated for this case.",
        )

    requested_format = format.lower().strip()
    if requested_format not in {"pdf", "json"}:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Unsupported report format. Use 'pdf' or 'json'.",
        )

    report_payload = {
        "meta": {
            "case_id": report.case_id,
            "case_title": case.title,
            "report_id": report.id,
            "generated_at": report.created_at.isoformat(),
        },
        "sections": report.sections,
        "trust_score": report.trust_score,
        "confidence_scores": report.confidence_scores,
        "explanation_graph": report.explanation_graph,
        "knowledge_graph": report.knowledge_graph,
    }
    generator = ReportGenerator()

    if requested_format == "json":
        output_path = Path(generator.output_dir) / f"report_{case_id}_{report.id}.json"
        output_path.write_text(json.dumps(report_payload, indent=2, default=str), encoding="utf-8")
        report.json_path = str(output_path)
        await db.commit()
        return FileResponse(
            output_path,
            media_type="application/json",
            filename=f"lexorch_report_{case_id}.json",
        )

    output_path = Path(generator.output_dir) / f"report_{case_id}_{report.id}.pdf"
    generated_path = Path(generator.generate_pdf(report_payload, str(output_path)))
    report.pdf_path = str(generated_path)
    await db.commit()
    media_type = "application/pdf" if generated_path.suffix == ".pdf" else "text/html"
    return FileResponse(
        generated_path,
        media_type=media_type,
        filename=f"lexorch_report_{case_id}{generated_path.suffix}",
    )
